/**
 * Vehicle catalogue: the 32 fictional cars (20 original, 12 ground cars added in the first fleet tranche). Data only. Checks are in vehicles/catalogue.ts, and the stat
 * pipeline is in vehicles/effectiveSpecs.ts.
 *
 * Format:
 * - `id` is a stable key that the save stores. Never rename an id. Retire it and add a migration instead. The first
 *   seven ids are legacy ids (see PROJECT_CONTEXT.md, Part 12); their display names follow the roster.
 * - `roster` is the 01..20 number shown in the garage. Prices rise with the roster number.
 * - `handling` holds only the tunable keys (specLimits.ts). Missing keys inherit VEHICLE_CONFIG. Every value sits
 *   inside SPEC_LIMITS, so no car leaves the stable envelope.
 * - `requiredRankId` is the career rank that unlocks purchase. The rank table is in career/careerCatalogue.ts.
 * - `design` is looked up from VEHICLE_DESIGNS by id (config/vehicleDesigns.ts). It is not stored here.
 *
 * Handling values are design intent, checked by the performance index (vehicles/performance.ts). The controller reads
 * them unchanged. Nothing here is a second calculation.
 */
